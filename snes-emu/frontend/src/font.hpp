// Map a UTF-8 Latin-1 accented byte (0xC3 0xA0..0xBF) to its ASCII base.
inline char latin1Base(uint8_t b) {
  switch (b) {
    case 0xA7: return 'c';
    case 0xB1: return 'n';
    case 0xB0: return 'd';
    case 0xB7: return '/';
    case 0xA6: return 'a';
    default: {
      // à-å (0xA0-A5) -> a, è-ë (0xA8-AB) -> e, ì-ï (0xAC-AF) -> i,
      // ò-ö (0xB2-B6) -> o, ù-ü (0xB9-BC) -> u, ý/ÿ -> y.
      if (b >= 0xA0 && b <= 0xA5) return 'a';
      if (b >= 0xA8 && b <= 0xAB) return 'e';
      if (b >= 0xAC && b <= 0xAF) return 'i';
      if (b >= 0xB2 && b <= 0xB6) return 'o';
      if (b >= 0xB9 && b <= 0xBC) return 'u';
      if (b == 0xBD || b == 0xBF) return 'y';
      if (b == 0xBE) return 'p';
      if (b == 0xB8) return 'o';
      return '?';
    }
  }
}

