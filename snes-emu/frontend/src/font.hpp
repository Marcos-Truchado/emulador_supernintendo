// Render `text` into a texture using the 8x8 font scaled by `scale`.
// Color is 8-bit RGB. Caller owns the returned texture (SDL_DestroyTexture).
inline SDL_Texture* renderText(SDL_Renderer* renderer, const std::string& text,
                               uint8_t r, uint8_t g, uint8_t b, int scale = 1) {
  const int gw = 8 * scale, gh = 8 * scale;

  // First pass: count columns (handling UTF-8 multi-byte sequences).
  int cols = 0;
  for (size_t i = 0; i < text.size(); i++) {
    if (static_cast<uint8_t>(text[i]) == 0xC3 && i + 1 < text.size()) i++;
    cols++;
  }

  const int w = cols * gw, h = gh;
  SDL_Surface* surf =
      SDL_CreateRGBSurfaceWithFormat(0, w, h, 32, SDL_PIXELFORMAT_RGBA32);
  if (!surf) return nullptr;

  // SDL_MapRGBA handles the byte order + alpha correctly for the format.
  const uint32_t fg = SDL_MapRGBA(surf->format, r, g, b, 255);
  const int pitch = surf->pitch / 4;  // row stride in pixels
  uint32_t* px = static_cast<uint32_t*>(surf->pixels);

  int col = 0;
  for (size_t i = 0; i < text.size(); i++) {
    uint8_t c = static_cast<uint8_t>(text[i]);
    if (c == 0xC3 && i + 1 < text.size()) {
      c = static_cast<uint8_t>(latin1Base(static_cast<uint8_t>(text[i + 1])));
      i++;
    }
    if (c < 32 || c > 126) c = 32;
    const uint8_t* glyph = kFont[c];
    for (int gy = 0; gy < 8; gy++) {
      for (int gx = 0; gx < 8; gx++) {
        if (glyph[gy] & (0x80 >> gx)) {
          for (int sy = 0; sy < scale; sy++) {
            for (int sx = 0; sx < scale; sx++) {
              px[(gy * scale + sy) * pitch + (col * gw + gx * scale + sx)] = fg;
            }
          }
        }
      }
    }
    col++;
  }

  SDL_Texture* tex = SDL_CreateTextureFromSurface(renderer, surf);
  SDL_FreeSurface(surf);
  return tex;
}
